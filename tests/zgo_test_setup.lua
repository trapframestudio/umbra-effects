-- the game's file system: scripts and meshes with sizes (fs_file.size_real)
FSF = {}
EXIST_CALLS = 0
local harness_getFS = getFS
local FS = {
	exist = function(self, root, p)
		EXIST_CALLS = EXIST_CALLS + 1
		local f = FSF[root .. "|" .. p]
		if f ~= nil then return f or nil end
		return FS_FILES[root .. "|" .. p] or nil
	end,
	update_path = function(self, root, name)
		assert(root == "$app_data_root$", "only appdata is written")
		return TMP .. "/appdata/" .. name
	end,
}
function getFS() return FS end
-- lfs (Windows paths are mapped onto TMP: "Z:\mo2\..." -> TMP/mo2/...)
local function real(p) return (p:gsub("^Z:\\", TMP .. "/"):gsub("\\", "/")) end
LFS_CALLS = 0
lfs = {
	attributes = function(p, what)
		LFS_CALLS = LFS_CALLS + 1
		local rp = real(p)
		local f = io.open(rp, "rb")
		if f then
			local ok, size = pcall(function() return f:seek("end") end)
			f:close()
			if ok and size then
				if what == "size" then return size end
				if what == "mode" then return "file" end
			end
		end
		if os.execute('test -d "' .. rp .. '"') == 0 then
			if what == "mode" then return "directory" end
			if what == "size" then return 0 end
		end
		return nil
	end,
}
-- io.open on "Z:\..." paths goes to TMP too
local real_open = io.open
io.open = function(p, mode) return real_open(p:match("^Z:\\") and real(p) or p, mode) end

local function write(path, bytes)
	os.execute('mkdir -p "' .. path:match("^(.*)/[^/]*$") .. '"')
	local f = assert(real_open(path, "wb"))
	f:write(string.rep("x", bytes))
	f:close()
end

-- a bake: index + inputs as bake.py writes them
local function bake(opts)
	opts = opts or {}
	local id = opts.id or "20261113-150000-abcdef01"
	local models_idx, models_in, n = {}, {}, opts.n or 40
	MODELS = {}
	for i = 1, n do
		local k = string.format("actors\\stalker_test\\stalker_%03d", i)
		MODELS[i] = k
		models_idx[k] = { bip01_head = true }
		local src = (i % 4 == 0) and 0 or ((i % 2) + 1)          -- the game, mod 1 or mod 2
		models_in[k] = string.format("%d %d %d", 1000 + i, src, 500 + i)
		FSF["$game_meshes$|" .. k .. ".ogf"] = { size_real = 1000 + i }
		if src > 0 then
			write(TMP .. "/mo2/mods/" .. (src == 1 and "Mod One" or "Mod Two") .. "/gamedata/meshes/" .. k:gsub("\\", "/") .. ".ogf", 500 + i)
		end
	end
	rawset(_G, "zgo_bake_index", { version = opts.version or 2, bake_id = id, models = models_idx })
	FS_FILES["$game_scripts$|zgo_bake_index.script"] = true
	FSF["$game_scripts$|zgo_bake_index.script"] = { size_real = 4321 }
	if opts.no_inputs then
		rawset(_G, "zgo_bake_inputs", nil)
		FS_FILES["$game_scripts$|zgo_bake_inputs.script"] = nil
		return
	end
	local inputs = {
		version = 1, bake_id = opts.inputs_id or id, baker = opts.baker or N.BAKER, zgo = "1.7.0",
		flags = "caps pieces wounds", fingerprint = "f",
		tables = opts.tables or N.canonical_tables(zgo_tables.limb_map),
		profile = "P", mo2 = "Z:\\mo2", zgo_mod = "Umbra Gore & Effects", index_bytes = opts.index_bytes or 4321,
		mods = { "Mod One", "Mod Two" }, models = models_in,
	}
	rawset(_G, "zgo_bake_inputs", inputs)
	FS_FILES["$game_scripts$|zgo_bake_inputs.script"] = true
	os.execute('mkdir -p "' .. TMP .. '/mo2/profiles/P"')
	local f = assert(real_open(TMP .. "/mo2/profiles/P/modlist.txt", "w"))
	f:write("# This file was automatically generated by Mod Organizer.\r\n+Umbra Gore & Effects\r\n+Mod One\r\n-Disabled Mod\r\n+Mod Two\r\n")
	f:close()
end

local function unbake()
	rawset(_G, "zgo_bake_index", nil)
	rawset(_G, "zgo_bake_inputs", nil)
	FS_FILES["$game_scripts$|zgo_bake_index.script"] = nil
	FS_FILES["$game_scripts$|zgo_bake_inputs.script"] = nil
	FSF = {}
end

local function forget() os.remove(TMP .. "/appdata/zgo_setup_notice.txt") end

-- run the check (forced = the MCM button) and wait until it is done
local function check(forced)
	NEWS, LOG = {}, {}
	if forced then N.check_now() else CB.actor_on_first_update() end
	local frames = 0
	repeat
		frame(16)
		frames = frames + (N.busy() and 1 or 0)
		assert(frames < 2000, "check never finished")
	until not N.busy() and T_NOW > 0
	run(100)
	return N.result(), frames
end

local function has(list, pat)
	for _, l in ipairs(list) do if l:find(pat, 1, true) then return true end end
	return false
end
local function log_has(pat) return has(LOG, pat) end
local function quiet_log()
	for _, l in ipairs(LOG) do
		assert(not (l:find("error") or l:find("failed") or l:find("traceback") or l:find("stopped")), "bad log line: " .. l)
	end
end

