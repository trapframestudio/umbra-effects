def write_db(path, files):
    """An X-Ray .db archive: data chunk 0, uncompressed file list chunk 1
    (xdb.Archive reads both; real == compressed means raw data)."""
    body = bytearray()
    ptrs = {}
    for name, raw in files.items():
        ptrs[name] = 8 + len(body)
        body += raw
    lst = bytearray()
    for name, raw in files.items():
        nb = name.encode('latin1')
        lst += struct.pack('<HIII', 12 + len(nb) + 4, len(raw), len(raw), 0) + nb + struct.pack('<I', ptrs[name])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(struct.pack('<II', 0, len(body)) + bytes(body) + struct.pack('<II', 1, len(lst)) + bytes(lst))


