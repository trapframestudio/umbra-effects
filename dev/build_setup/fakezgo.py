def effect_bytes(shader, texture):
    """A small .pe as the SDK writes them (CRLF)."""
    lines = ['[_effect]', '        action_count                     = 0', '        flags                            = 1',
             '        max_particles                    = 10', '        version                          = 1', ' ',
             '[sprite]', '        shader                           = ' + shader,
             '        texture                          = ' + texture, ' ',
             '[timelimit]', '        value                            = 0.500000', '']
    return '\r\n'.join(lines).encode('latin1')


def group_bytes(effects):
    lines = ['[_group]', '        effects_count                    = %d' % len(effects),
             '        flags                            = 0', '        timelimit                        = 5.000000',
             '        version                          = 3', ' ']
    for i, name in enumerate(effects):
        lines += ['[effect_%04d]' % i, '        effect_name                      = ' + name,
                  '        flags                            = 4', '        on_birth_child                   =',
                  '        on_death_child                   =', '        on_play_child                    =',
                  '        time0                            = 0.000000', ' ']
    return '\r\n'.join(lines + ['']).encode('latin1')


def particles_xr_bytes(effects, groups=None):
    """A particles.xr as the game reads it (tools/zgo_kidfx/particles_xr.py has the format):
    effects {name: (shader, texture)}, each with one 'killold' action; groups {name: (effects)}.
    The compiled action list (chunk 4) is a stand-in: the game rebuilds it from chunk 0x24."""
    def chunk(cid, body):
        return struct.pack('<II', cid, len(body)) + body

    def sz(s):
        return s.encode('latin1') + b'\0'
    pe = []
    for i, (name, (shader, tex)) in enumerate(sorted(effects.items())):
        edata = struct.pack('<III', 1, 10, 1) + sz('killold') + struct.pack('<IfB', 1, 0.75, 0)
        body = (chunk(1, struct.pack('<H', 1)) + chunk(2, sz(name)) + chunk(3, struct.pack('<I', 10)) +
                chunk(4, b'\0' * 4) + chunk(5, struct.pack('<I', 1 | (1 << 14))) + chunk(7, sz(shader) + sz(tex)) +
                chunk(8, struct.pack('<f', 0.5)) + chunk(0x24, edata))
        pe.append(chunk(i, body))
    pg = []
    for i, (name, kids) in enumerate(sorted((groups or {}).items())):
        ents = struct.pack('<I', len(kids)) + b''.join(sz(k) + sz('') * 3 + struct.pack('<ffI', 0, 0.25, 4)
                                                       for k in kids)
        body = (chunk(1, struct.pack('<H', 3)) + chunk(2, sz(name)) + chunk(3, struct.pack('<I', 0)) +
                chunk(4, ents) + chunk(5, struct.pack('<f', 5.0)))
        pg.append(chunk(i, body))
    return chunk(1, struct.pack('<H', 1)) + chunk(3, b''.join(pe)) + chunk(4, b''.join(pg))


def shaders_xr():
    """A shaders.xr holding the four stock particle blenders, in the layout
    tools/zgo_kidfx/sc_blenders.py reads: chunk 2, one sub-chunk per blender,
    CBlender_DESC (176 bytes) then the properties (u32 type, name, value)."""
    def prop(kind, name, payload=b''):
        return struct.pack('<I', kind) + name.encode('latin1') + b'\0' + payload
    MARKER, INTEGER, BOOL, TOKEN = 0, 4, 6, 7
    body = bytearray()
    for i, (name, blend, prio, strict, clamp) in enumerate(BLENDERS):
        desc = (b'PARTICLE'[::-1] + name.encode('latin1').ljust(128, b'\0') + b'fakezgo'.ljust(32, b'\0') +
                struct.pack('<IH', 0, 1)).ljust(176, b'\0')
        props = (prop(MARKER, 'General') + prop(INTEGER, 'Priority', struct.pack('<iii', prio, 0, 3)) +
                 prop(BOOL, 'Strict sorting', struct.pack('<i', int(strict))) +
                 prop(TOKEN, 'Blending', struct.pack('<II', blend, len(BLEND_NAMES)) + b''.join(
                     struct.pack('<I', j) + n.encode('latin1').ljust(64, b'\0') for j, n in enumerate(BLEND_NAMES))) +
                 prop(INTEGER, 'Alpha ref', struct.pack('<iii', 32, 0, 255)) +
                 prop(BOOL, 'Texture clamp', struct.pack('<i', int(clamp))))
        sub = desc + props
        body += struct.pack('<II', i, len(sub)) + sub
    return struct.pack('<II', 2, len(body)) + bytes(body)


def _put(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data)


def add_kidfx(inst, zgo_dir=None):
    """Kid mode for particles in this fake install: tools/zgo_kidfx's .py files
    (a fresh, empty kidfx_copies.json; never the real one) and ZGO's shipped
    effects in zgo_dir (default: the install's ZGO folder), and the game side
    (stock shaders, shaders.xr, effects to copy) in the game's loose gamedata."""
    zgo_dir = zgo_dir or inst.mod
    kd = os.path.join(zgo_dir, 'tools', 'zgo_kidfx')
    os.makedirs(kd, exist_ok=True)
    for fn in sorted(os.listdir(KIDFX_SRC)):
        if fn.endswith('.py'):
            shutil.copyfile(os.path.join(KIDFX_SRC, fn), os.path.join(kd, fn))
    with open(os.path.join(kd, 'kidfx_copies.json'), 'w') as f:
        json.dump({'copies': {}}, f, indent=1, sort_keys=True)
    part = os.path.join(zgo_dir, 'gamedata', 'particles')
    for rel, (shader, tex) in ZGO_EFFECTS.items():
        _put(os.path.join(part, *rel.split('/')), effect_bytes(shader, tex))
    for rel, kids in ZGO_GROUPS.items():
        _put(os.path.join(part, *rel.split('/')), group_bytes(kids))
    gd = os.path.join(inst.game, 'gamedata')
    _put(os.path.join(gd, 'shaders', 'r3', 'particle.ps'), STOCK_PS.encode('latin1'))
    _put(os.path.join(gd, 'shaders', 'r3', 'deffer_particle.ps'), STOCK_PS.replace('* I.c', '').encode('latin1'))
    _put(os.path.join(gd, 'shaders.xr'), shaders_xr())
    for rel, (shader, tex) in GAME_EFFECTS.items():
        _put(os.path.join(gd, 'particles', *rel.split('/')), effect_bytes(shader, tex))
    for rel, kids in GAME_GROUPS.items():
        _put(os.path.join(gd, 'particles', *rel.split('/')), group_bytes(kids))
    return kd


# ---------------------------------------------------------------- a ready-made bake's bucket

def _path_forms(path):
    """How a path of this machine appears in the bake's text files (Umbra's dev/pack_build.py
    path_forms, without its /var/home twin)."""
    forms = set()
    for v in {os.path.normpath(path), os.path.realpath(path)}:
        win = 'Z:' + v.replace('/', '\\')
        forms |= {('', v), ('_WIN', win), ('_WIN_ESC', win.replace('\\', '\\\\')), ('_WIN', 'Z:' + v)}
    return sorted(forms, key=lambda f: -len(f[1]))


def publish_bake(out, bucket, mo2, anomaly, caches, profile, zgo_folder, volume_files=3):
    """Pack the bake in out the way Umbra's dev/pack_build.py does into bucket (a folder laid
    out like the bucket, see tools/zgo_setup/prebaked.py): this machine's paths and the
    profile and folder names become @@UMBRA_*@@ tokens, a report volume, volumes, the
    manifest and umbra-effects/index.json. Returns (manifest, its index entry)."""
    import hashlib
    import re
    import zipfile
    sys.path.insert(0, os.path.join(MOD, 'tools', 'zgo_fracture'))
    import bake
    import fracture
    reports = [r for r in (bake.REPORT, fracture.REPORT) if os.path.isfile(os.path.join(out, r))]
    files = []
    for r in reports:
        with open(os.path.join(out, r), encoding='utf-8') as f:
            files += [x for x in json.load(f).get('files', []) if os.path.isfile(os.path.join(out, *x.split('/')))]
    data, relocate = {}, []
    names = {'profile': ({profile}, '@@UMBRA_PROFILE@@'), 'zgo_mod': ({zgo_folder}, '@@UMBRA_ZGO_FOLDER@@')}
    for rel in reports + sorted(set(files)):
        with open(os.path.join(out, *rel.split('/')), 'rb') as f:
            raw = f.read()
        if rel.endswith(('.json', '.script')):
            text, n = raw.decode('utf-8'), 0
            for name, base in [('MO2', mo2), ('ANOMALY', anomaly)] + [('ZGO_CACHE', c) for c in caches]:
                for suffix, form in _path_forms(base):
                    n += text.count(form)
                    text = text.replace(form, '@@UMBRA_%s%s@@' % (name, suffix))
            if rel in reports:
                rep = json.loads(text)

                def walk(node):
                    if isinstance(node, dict):
                        for k, v in node.items():
                            if k in names and v in names[k][0]:
                                node[k] = names[k][1]
                            else:
                                walk(v)
                    elif isinstance(node, list):
                        for v in node:
                            walk(v)
                walk(rep)
                text, n = json.dumps(rep, indent=1, sort_keys=True), n + 1
            elif rel == bake.INPUTS:
                for k, (was, tok) in names.items():
                    text = re.sub(r'(?m)^%s = "(?:%s)"' % (k, '|'.join(re.escape(w) for w in was)),
                                  '%s = "%s"' % (k, tok), text)
                n += 1
            if n:
                relocate.append(rel)
                raw = text.encode('utf-8')
        data[rel] = raw
    with open(os.path.join(out, bake.REPORT), encoding='utf-8') as f:
        rep = json.load(f)
    fp = rep['inputs']['fingerprint']
    rest = [r for r in data if r not in reports]
    vols = [reports] + [rest[i:i + volume_files] for i in range(0, len(rest), volume_files)]
    d = os.path.join(bucket, 'umbra-effects', fp)
    os.makedirs(d, exist_ok=True)
    objs = []
    for v in vols:
        tmp = os.path.join(d, 'volume.tmp')
        with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as z:
            for rel in v:
                z.writestr(zipfile.ZipInfo(rel, (2020, 1, 1, 0, 0, 0)), data[rel], zipfile.ZIP_DEFLATED)
        with open(tmp, 'rb') as f:
            sha = hashlib.sha256(f.read()).hexdigest()
        os.replace(tmp, os.path.join(d, sha + '.zip'))
        objs.append({'path': 'umbra-effects/%s/%s.zip' % (fp, sha), 'sha256': sha,
                     'size': os.path.getsize(os.path.join(d, sha + '.zip')), 'files': len(v),
                     'bytes': sum(len(data[r]) for r in v)})
    man = {'format': 1, 'kind': 'umbra-effects-bake', 'fingerprint': fp, 'baker': rep['inputs'].get('baker', 0),
           'zgo': rep['inputs'].get('zgo', ''), 'made': rep.get('time', ''), 'models': rep.get('baked', 0),
           'files': len(data), 'bytes': sum(len(x) for x in data.values()), 'relocate': sorted(relocate),
           'report': objs[0], 'volumes': objs[1:]}
    blob = (json.dumps(man, indent=1, sort_keys=True) + '\n').encode('utf-8')
    sha = hashlib.sha256(blob).hexdigest()
    with open(os.path.join(d, sha + '.json'), 'wb') as f:
        f.write(blob)
    entry = {'path': 'umbra-effects/%s/%s.json' % (fp, sha), 'sha256': sha, 'size': len(blob), 'fingerprint': fp,
             'baker': man['baker'], 'zgo': man['zgo'], 'made': man['made'], 'models': man['models'],
             'download': sum(o['size'] for o in objs[1:]), 'bytes': man['bytes']}
    write_index(bucket, [entry])
    return man, entry


def write_index(bucket, entries):
    os.makedirs(os.path.join(bucket, 'umbra-effects'), exist_ok=True)
    with open(os.path.join(bucket, 'umbra-effects', 'index.json'), 'w') as f:
        json.dump({'format': 1, 'kind': 'umbra-effects-bakes', 'bakes': entries}, f, indent=1)


class Install:
    def __init__(self, root, zgo):
        self.root = root
        self.mo2 = os.path.join(root, 'mo2')
        self.game = os.path.join(root, 'game')
        self.mod = os.path.join(self.mo2, 'mods', zgo)
        self.zgo = zgo
        self.profile = 'P'
        self.cache = os.path.join(root, 'cache')

    def model(self, mod, key):
        return os.path.join(self.mo2, 'mods', mod, 'gamedata', 'meshes', *key.split('\\')) + '.ogf'


def make(root, tools=True, zgo=ZGO, version='1.7.0', kidfx=None):
    """A fake install under root. tools=True: ZGO's folder is a working copy
    of the tools (for running zgo_setup.py from there); False: an empty
    folder to bake into. kidfx (default: = tools): add_kidfx()."""
    i = Install(root, zgo)
    os.makedirs(os.path.join(i.mo2, 'mods'), exist_ok=True)
    for k in MOD_MODELS:
        write_model(i.mo2, 'Synth Models', k)
    set_modlist(i.mo2, 'P', ['+' + zgo, '+Synth Models'])
    set_modlist(i.mo2, 'Other', ['+Synth Models'])
    os.makedirs(i.mod, exist_ok=True)
    if tools:
        copy_tools(i.mod)
        sd = os.path.join(i.mod, 'gamedata', 'scripts')
        os.makedirs(sd, exist_ok=True)
        with open(os.path.join(sd, 'zgo_main.script'), 'w', newline='') as f:
            f.write('VERSION = "%s"\r\nfunction on_game_start() end\r\n' % version)
        with open(os.path.join(sd, 'zgo_tables.script'), 'w', newline='') as f:
            f.write(TABLES.replace('\n', '\r\n'))
        with open(os.path.join(i.mod, 'meta.ini'), 'w') as f:
            f.write('[General]\nversion=%s\n' % version)
    write_db(os.path.join(i.game, 'db', 'meshes', 'meshes_actors.db0'),
             {'meshes\\' + k + '.ogf': synth.build() for k in GAME_MODELS})
    write_db(os.path.join(i.game, 'db', 'meshes', 'meshes.db0'), {'textures\\nothing.dds': b'DDS '})
    os.makedirs(os.path.join(i.game, 'bin'), exist_ok=True)
    game_win = 'Z:' + i.game.replace('/', '\\\\')
    with open(os.path.join(i.mo2, 'ModOrganizer.ini'), 'w') as f:
        f.write('[General]\ngameName=Anomaly\nselected_profile=@ByteArray(P)\ngamePath=@ByteArray(%s)\n' % game_win)
    if kidfx is None:
        kidfx = tools
    if kidfx:
        add_kidfx(i)
    return i


