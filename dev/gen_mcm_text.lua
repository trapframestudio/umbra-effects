--[[
  Writes the MCM string tables from gamedata/scripts/zgo_settings.script
  (the one place every option's name and explanation live):
    gamedata/configs/text/eng/ui_st_zgo_mcm.xml
    gamedata/configs/text/rus/ui_st_zgo_mcm.xml   (windows-1251)

  luajit dev/gen_mcm_text.lua           write both files
  luajit dev/gen_mcm_text.lua --check   exit 1 if they are out of date (tests use this)

  Run from the mod's root folder (dev/run.sh does that).
]]

local check = arg[1] == "--check"

-- load scripts the way the game does: a global named like a script file is that script
local env
local function load_script(name, into)
	local path = "gamedata/scripts/" .. name .. ".script"
	local f = io.open(path, "r")
	if not f then return nil end
	f:close()
	local menv = into or setmetatable({}, { __index = env })
	local chunk = assert(loadfile(path))
	setfenv(chunk, menv)
	chunk()
	return menv
end
env = setmetatable({}, { __index = function(t, k)
	local v = _G[k]
	if v ~= nil then return v end
	if type(k) == "string" and k:match("^zgo_settings_") then
		local m = load_script(k)
		rawset(t, k, m or false)
		return m
	end
end })
rawset(env, "_G", env)   -- zgo_settings looks feature files up as _G[name], like the game
load_script("zgo_settings", env)

-- UTF-8 -> windows-1251 (Cyrillic and the few symbols the texts use)
local CP = { [0x0401] = 0xA8, [0x0451] = 0xB8, [0x2014] = 0x97, [0x2013] = 0x96, [0x00AB] = 0xAB, [0x00BB] = 0xBB, [0x2116] = 0xB9 }
local function to1251(s, where)
	local out = {}
	local i = 1
	while i <= #s do
		local c = s:byte(i)
		local cp, n
		if c < 0x80 then cp, n = c, 1
		elseif c >= 0xC0 and c < 0xE0 then cp, n = (c - 0xC0) * 64 + (s:byte(i + 1) - 0x80), 2
		elseif c >= 0xE0 and c < 0xF0 then cp, n = ((c - 0xE0) * 64 + (s:byte(i + 1) - 0x80)) * 64 + (s:byte(i + 2) - 0x80), 3
		else error("unsupported UTF-8 in " .. where) end
		local b
		if cp < 0x80 then b = cp
		elseif cp >= 0x0410 and cp <= 0x044F then b = cp - 0x0410 + 0xC0
		else b = CP[cp] end
		if not b then error(string.format("no windows-1251 for U+%04X in %s", cp, where)) end
		out[#out + 1] = string.char(b)
		i = i + n
	end
	return table.concat(out)
end

local function esc(s)
	return (s:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"))
end

local function build(lang)
	local lines = { '<?xml version="1.0" encoding="windows-1251"?>',
		"<!-- Generated by dev/gen_mcm_text.lua from zgo_settings.script; edit the texts there. -->",
		"<string_table>" }
	for _, e in ipairs(env.strings(lang)) do
		assert(e[2] and e[2] ~= "", "empty text for " .. e[1])
		local text = esc(e[2])
		if lang == 2 then text = to1251(text, e[1]) end
		lines[#lines + 1] = string.format('\t<string id="%s"><text>%s</text></string>', e[1], text)
	end
	lines[#lines + 1] = "</string_table>"
	return table.concat(lines, "\r\n") .. "\r\n"
end

local stale = 0
for lang, dir in ipairs({ "eng", "rus" }) do
	local path = "gamedata/configs/text/" .. dir .. "/ui_st_zgo_mcm.xml"
	local want = build(lang)
	local f = io.open(path, "rb")
	local have = f and f:read("*a")
	if f then f:close() end
	if have ~= want then
		if check then
			print("out of date: " .. path .. " (run luajit dev/gen_mcm_text.lua)")
			stale = stale + 1
		else
			local w = assert(io.open(path, "wb"))
			w:write(want)
			w:close()
			print("wrote " .. path)
		end
	end
end
os.exit(stale == 0 and 0 or 1)
