"""
The generated scripts (formats in docs/formats/index.md, parts.md, wounds.md):

  zgo_bake_index.script   models[visual] = { [section root] = true }  (as since
                          1.4; plus bake_id and features)
  zgo_bake_parts.script   per model and section: its sub-mesh ids, stump cap,
                          limb piece, body gibs; experimental K_s / D_s ids and
                          gib chunks
  zgo_bake_wounds.script  wound sites per section geometry, bind poses per
                          skeleton

All three carry the same bake_id; zgo_bake.script ignores parts / wounds from
another bake. Anomaly loads every script in the scripts folder at game start
(axr_main.on_game_start), so the big tables are one string per entry, shared
through numbered lists, and decoded on first use.
"""
import os

INDEX_VERSION = 2
PARTS_VERSION = 1
WOUNDS_VERSION = 1
HEADER = '-- Generated by the Umbra Effects mesh baker (tools/zgo_baker/bake.py). Do not edit.'


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_lines(out_root, rel, lines):
    p = os.path.join(out_root, *rel.split('/'))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p + '.part', 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    os.replace(p + '.part', p)


class Interner:
    """Numbered list of unique strings (1-based, as Lua arrays)."""

    def __init__(self):
        self.items, self.ids = [], {}

    def __call__(self, s):
        i = self.ids.get(s)
        if i is None:
            self.items.append(s)
            i = self.ids[s] = len(self.items)
        return i


def _list(name, items, per_line=1):
    out = ['%s = {' % name]
    if per_line == 1:
        out += ['\t%s,' % lua_str(s) for s in items]
    else:
        for i in range(0, len(items), per_line):
            out.append('\t' + ' '.join('%s,' % lua_str(s) for s in items[i:i + per_line]))
    out.append('}')
    return out


def _models(entries):
    out = ['models = {']
    out += ['\t[%s] = %s,' % (lua_str(k), lua_str(v)) for k, v in entries]
    out.append('}')
    return out


def index_lines(ok, bake_id, features):
    """ok: results sorted by key, with 'key' and 'sections'."""
    sets, names = {}, []
    for r in ok:
        k = tuple(r['sections'])
        if k not in sets:
            sets[k] = 'S%d' % (len(sets) + 1)
            names.append(k)
    lines = [HEADER,
             '-- models[visual] = set of section roots that are separate sub-meshes.',
             '-- docs/formats/index.md. zgo_bake_parts / zgo_bake_wounds hold the rest.',
             'version = %d' % INDEX_VERSION, 'bake_id = %s' % lua_str(bake_id),
             'features = { %s }' % ', '.join('%s = %s' % (k, 'true' if v else 'false')
                                             for k, v in sorted(features.items())),
             '']
    for k in names:
        lines.append('local %s = { %s }' % (sets[k], ', '.join('%s = true' % b for b in k)))
    lines.append('')
    lines.append('models = {')
    for r in ok:
        lines.append('\t[%s] = %s,' % (lua_str(r['key']), sets[tuple(r['sections'])]))
    lines.append('}')
    return lines


def parts_lines(bake_id, names, bonesets, entries, gibsets=()):
    """entries: [(visual key, encoded line)]; names / bonesets / gibsets: lists."""
    return [HEADER,
            '-- Sub-meshes, stump caps and limb pieces per model and section (docs/formats/parts.md).',
            '-- models[visual] = "sec:ids/cap/piece[/k:ids][/d:c=d,..][/g:chunks][/b:gibs] ..." where sec',
            '-- indexes names, cap is <file hash>.<bonesets index>, piece a file hash ("-" = none) and',
            '-- gibs <file hash>.<gibsets index> (docs/formats/gibs.md).',
            'version = %d' % PARTS_VERSION, 'bake_id = %s' % lua_str(bake_id), '',
            *_list('names', names, 8), '',
            *_list('bonesets', bonesets), '',
            *_list('gibsets', gibsets), '',
            *_models(entries)]


def wounds_lines(bake_id, names, skels, sites, entries):
    return [HEADER,
            '-- Wound sites and bind poses (docs/formats/wounds.md).',
            '-- skels[i] = "name,parent,qw,qx,qy,qz,cx,cy,cz;..." quaternion x10000, origin in 0.1 mm',
            '-- sites[i] = "bone,x,y,z,nx,ny,nz,thick,radius,depth,hint;..." mm, normal x100',
            '-- models[visual] = "skel sec=sites sec=sites ..." (indexes into skels, names, sites)',
            'version = %d' % WOUNDS_VERSION, 'bake_id = %s' % lua_str(bake_id), '',
            *_list('names', names, 8), '',
            *_list('skels', skels), '',
            *_list('sites', sites), '',
            *_models(entries)]
